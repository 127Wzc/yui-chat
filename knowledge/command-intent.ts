/** 识别值得优先提供知识工具的明确请求；其他请求仍由模型结合上下文选择工具。 */
export function isBotCommandQuery(prompt: string): boolean {
  return /(?:机器人|bot|插件|yui(?:-chat)?).{0,20}(?:指令|命令|功能|权限|参数|触发条件|能做什么|有哪些能力|有什么能力|怎么用|如何用|使用方法)|(?:怎么|如何|怎样).{0,16}(?:入群验证|查体力)|(?:^|[\s（(])[#/*!][^\s/]{1,40}.{0,12}(?:怎么用|如何用|用法|参数|权限|触发)|(?:查|搜|检索|查看|参考|根据|从|列出|读取).{0,12}(?:知识库|资料库)|(?:知识库|资料库).{0,12}(?:查|搜|检索|资料|内容|有哪些|有什么|怎么用|如何用)/iu.test(prompt)
}
